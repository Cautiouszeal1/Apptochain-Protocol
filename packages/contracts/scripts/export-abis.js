// Copies compiled ABIs into the SDK so it never drifts from the contracts.
// Run after `npx hardhat compile` (npm run abis does both).
const fs = require("fs");
const path = require("path");
const names = ["ATCFactory", "ATCForwarder", "ATCTreasury", "ATCMembership", "ATCAssets", "ATCRewards", "ATCPayments"];
const outDir = path.join(__dirname, "..", "..", "sdk", "src", "abi");
fs.mkdirSync(outDir, { recursive: true });
const index = [];
for (const n of names) {
  const sub = ["ATCFactory", "ATCForwarder", "ATCTreasury"].includes(n) ? "core" : "templates";
  const art = require(path.join(__dirname, "..", "artifacts", "contracts", sub, `${n}.sol`, `${n}.json`));
  fs.writeFileSync(path.join(outDir, `${n}.ts`), `// Generated by contracts/scripts/export-abis.js — do not edit.\nexport default ${JSON.stringify(art.abi)} as const;\n`);
  index.push(`export { default as ${n}Abi } from "./${n}.js";`);
}
fs.writeFileSync(path.join(outDir, "index.ts"), index.join("\n") + "\n");
console.log(`Exported ${names.length} ABIs to ${outDir}`);
